function getSizesForProduct(p: SeedProduct): string[] {
  if (p.subcategory === "Sepatu") {
    return p.category === "anak"
      ? ["28", "30", "32", "34", "36"]
      : ["37", "38", "39", "40", "41", "42", "43"];
  }
  if (p.subcategory === "Tas" || p.subcategory === "Aksesoris" || p.subcategory === "Skincare & Makeup") {
    return ["All Size"];
  }
  if (p.category === "anak") {
    return ["2-3 Thn", "4-5 Thn", "6-7 Thn", "8-9 Thn"];
  }
  return ["S", "M", "L", "XL"];
}

